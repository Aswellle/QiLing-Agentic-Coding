// 帽子行（12字符，与 CC 精确一致）
const HAT_LINES: Record<Hat, string> = {
  none:      '',
  crown:     '   \\^^^/    ',
  tophat:    '   [___]    ',
  propeller: '    -+-     ',
  halo:      '   (   )    ',
  wizard:    '    /^\\     ',
  beanie:    '   (___)    ',
  tinyduck:  '    ,>      ',
}

export function renderSprite(bones: CompanionBones, frame = 0): string[] {
  const frames = BODIES[bones.species]
  const body = frames[frame % frames.length]!.map(line =>
    line.replaceAll('{E}', bones.eye),
  )
  const lines = [...body]
  // 用帽子替换空白的 hat slot 行
  if (bones.hat !== 'none' && !lines[0]!.trim()) {
    lines[0] = HAT_LINES[bones.hat]
  }
  // 如果所有帧的第 0 行都是空白，则去掉（节省垂直空间）
  if (!lines[0]!.trim() && frames.every(f => !f[0]!.trim())) {
    lines.shift()
  }
  return lines
}

export function spriteFrameCount(species: Species): number {
  return BODIES[species].length
}

export function renderFace(bones: CompanionBones): string {
  const e: Eye = bones.eye
  switch (bones.species) {
    case 'duck':      return `(${e}>`
    case 'goose':     return `(${e}>`
    case 'blob':      return `(${e}${e})`
    case 'cat':       return `=${e}ω${e}=`
    case 'dragon':    return `<${e}~${e}>`
    case 'octopus':   return `~(${e}${e})~`
    case 'owl':       return `(${e})(${e})`
    case 'penguin':   return `(${e}>)`
    case 'turtle':    return `[${e}_${e}]`
    case 'snail':     return `${e}(@)`
    case 'ghost':     return `/${e}${e}\\`
    case 'axolotl':   return `}${e}.${e}{`
    case 'capybara':  return `(${e}oo${e})`
    case 'cactus':    return `|${e}  ${e}|`
    case 'robot':     return `[${e}${e}]`
    case 'rabbit':    return `(${e}..${e})`
    case 'mushroom':  return `|${e}  ${e}|`
    case 'chonk':     return `(${e}.${e})`
    // 植物系 — 原创
    case 'sprout':       return `(${e}^${e})`        // 种荚小脸，^形嘴
    case 'fern':         return `//${e}${e}\\\\`      // 蕨叶包裹脸
    case 'sunflower':    return `*(${e}${e})*`        // 圆形花心，花瓣星号框
    case 'chrysanthemum':return `·(${e}.${e})·`      // 细瓣包裹，点状嘴
    case 'peony':        return `((${e} ${e}))`       // 层叠花瓣里的华贵脸庞
  }
}
